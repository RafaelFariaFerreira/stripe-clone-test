/**
 * Builds `src/registry.ts` from the SVG files in `svg/`.
 *
 * Each icon is stored as its viewBox plus inner markup, so React can render it
 * with a single <svg> element and Angular can bind it after trusting the
 * (static, first-party) markup. File names become the `IconName` union, which
 * turns a misspelled icon into a compile error in both apps.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const svgDir = join(root, 'svg');

const entries = readdirSync(svgDir)
  .filter((file) => file.endsWith('.svg'))
  .sort()
  .map((file) => {
    const svg = readFileSync(join(svgDir, file), 'utf8').trim();
    const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
    const body = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)?.[1]?.trim();
    if (!viewBox || !body) throw new Error(`Invalid SVG: ${file}`);
    const name = file.replace(/\.svg$/, '');
    // Brand marks keep their own colors; every other glyph inherits currentColor.
    const multicolor = /^(card|wallet)-/.test(name) && name !== 'card-generic';
    return { name, viewBox, body: body.replace(/\s+/g, ' '), multicolor };
  });

const lines = entries.map(
  (entry) =>
    `  ${JSON.stringify(entry.name)}: { viewBox: ${JSON.stringify(entry.viewBox)}, multicolor: ${entry.multicolor}, body: ${JSON.stringify(entry.body)} },`,
);

writeFileSync(
  join(root, 'src', 'registry.ts'),
  `/* Generated by scripts/generate.mjs from svg/*.svg. Do not edit by hand. */\n\nexport const ICONS = {\n${lines.join('\n')}\n} as const;\n`,
);
console.log(`Generated ${entries.length} icons.`);
